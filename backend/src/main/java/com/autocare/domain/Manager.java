package com.autocare.domain;

import jakarta.persistence.Column;
import jakarta.persistence.DiscriminatorValue;
import jakarta.persistence.Entity;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.List;

/**
 * Demonstrates Inheritance, Encapsulation, and Dynamic Polymorphism:
 * Manager extends Employee and overrides calculateSalary() to incorporate monthly managerial bonuses.
 * Provides authorized business methods such as discount approvals and low-stock report generation.
 */
@Entity
@DiscriminatorValue("MANAGER")
public class Manager extends Employee {

    @Column(name = "monthly_bonus", precision = 10, scale = 2)
    private BigDecimal monthlyBonus;

    /**
     * Protected no-arg constructor required by JPA.
     */
    protected Manager() {
        super();
    }

    /**
     * Parameterized constructor for Manager.
     *
     * @param id           unique UUID identifier
     * @param name         full manager name
     * @param phone        contact telephone number
     * @param email        email address
     * @param baseSalary   monthly base salary
     * @param monthlyBonus monthly managerial bonus (must be >= 0)
     */
    public Manager(String id, String name, String phone, String email, double baseSalary, double monthlyBonus) {
        super(id, name, phone, email, baseSalary);
        if (monthlyBonus < 0) {
            throw new IllegalArgumentException("Monthly bonus cannot be negative");
        }
        this.monthlyBonus = BigDecimal.valueOf(monthlyBonus).setScale(2, RoundingMode.HALF_UP);
    }

    public double getMonthlyBonus() {
        return monthlyBonus != null ? monthlyBonus.doubleValue() : 0.0;
    }

    /**
     * Updates monthly bonus amount with invariant validation.
     *
     * @param bonus positive bonus amount
     */
    public void setMonthlyBonus(double bonus) {
        if (bonus < 0) {
            throw new IllegalArgumentException("Monthly bonus cannot be negative");
        }
        this.monthlyBonus = BigDecimal.valueOf(bonus).setScale(2, RoundingMode.HALF_UP);
    }

    /**
     * Demonstrates dynamic polymorphism: overrides Employee.calculateSalary().
     * Calculates total salary as: baseSalary + monthlyBonus.
     *
     * @return calculated monthly salary
     */
    @Override
    public double calculateSalary() {
        BigDecimal bonus = this.monthlyBonus != null ? this.monthlyBonus : BigDecimal.ZERO;
        return this.baseSalary.add(bonus).setScale(2, RoundingMode.HALF_UP).doubleValue();
    }

    /**
     * Authorizes and applies a percentage discount to a given invoice.
     *
     * @param invoice invoice to receive discount
     * @param rate    percentage discount (0 - 100)
     * @throws IllegalArgumentException if invoice is null
     */
    public void approveDiscount(Invoice invoice, double rate) {
        if (invoice == null) {
            throw new IllegalArgumentException("Invoice cannot be null");
        }
        invoice.applyDiscount(rate, getId());
    }

    /**
     * Generates a text summary report of low-stock inventory items.
     * The service layer queries and passes items in, keeping the domain repository-free.
     *
     * @param items list of inventory items to inspect
     * @return formatted report string
     */
    public String generateInventoryReport(List<InventoryItem> items) {
        StringBuilder sb = new StringBuilder();
        sb.append("=== LOW STOCK INVENTORY REPORT ===\n");
        sb.append(String.format("Generated by Manager: %s (%s)\n\n", getName(), getId()));

        if (items == null || items.isEmpty()) {
            sb.append("No items provided or all stock levels healthy.\n");
            return sb.toString();
        }

        List<InventoryItem> lowStock = items.stream().filter(InventoryItem::isLowStock).toList();
        if (lowStock.isEmpty()) {
            sb.append("All inventory items currently above reorder thresholds.\n");
        } else {
            sb.append(String.format("%-15s %-25s %-10s %-10s\n", "Part Code", "Part Name", "Stock", "Threshold"));
            sb.append("---------------------------------------------------------------\n");
            for (InventoryItem item : lowStock) {
                sb.append(String.format(
                        "%-15s %-25s %-10d %-10d\n",
                        item.getPartCode(), item.getPartName(), item.getStockQuantity(), item.getReorderThreshold()
                ));
            }
        }
        return sb.toString();
    }

    /**
     * Parameterless report generation overload.
     *
     * @return empty report header
     */
    public String generateInventoryReport() {
        return generateInventoryReport(List.of());
    }

    @Override
    public String getEmployeeRole() {
        return "MANAGER";
    }

    @Override
    public String describe() {
        return String.format(
                "Manager[id=%s, name=%s, role=%s, baseSalary=%.2f, monthlyBonus=%.2f, totalSalary=%.2f]",
                getId(), getName(), getEmployeeRole(), getBaseSalary(), getMonthlyBonus(), calculateSalary()
        );
    }
}
